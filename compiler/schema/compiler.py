class Registry:
    """Every symbol emitted, de-duplicated."""

    def __init__(self) -> None:
        self.enums: dict[str, Enum] = {}
        self.models: list[Model] = []
        self.aliases: list[Alias] = []
        self.methods: list[Method] = []
        self._by_signature: dict[tuple, Model] = {}

    @property
    def units(self) -> list:
        return [*self.enums.values(), *self.models, *self.aliases, *self.methods]

    @property
    def enum_members(self) -> dict[str, list[str]]:
        return {e.name: e.values for e in self.enums.values()}

    def symbol_table(self) -> dict[str, tuple[str, str]]:
        table = {u.name: (u.package, u.module) for u in self.units}

        # Whatever the hand-written kept module of each package exports.
        for package in PACKAGES:
            for name in base_exports(package):
                table[name] = (package, KEPT_MODULE)

        return table

    # --- enums ---

    def enum(self, name: str, values: list[str], path: str) -> str:
        """Register the enum class the schema titled `name`.

        The same title is expected to carry the same members everywhere it
        appears; if it does not, the first one wins and the clash is reported
        rather than silently resolved.
        """

        if (existing := self.enums.get(name)) is not None:
            if existing.values != values:
                print(f"  ! {name} at {path} has different members; keeping the first")

            return name

        self.enums[name] = Enum(name, values)
        return name

    # --- models ---

    def model(self, name: str, fields: list[ModelField], inline: list[Model]) -> str:
        """Register a public result model, folding it into an existing one.

        An exact structural match is subclassed with an empty body -- the name
        is public API, so it has to stay even when the shape is a repeat.
        Otherwise the largest existing model whose fields are a leading subset
        becomes the base, and only the remaining fields are emitted.

        Only public models take part: the anonymous ones live inside whichever
        file uses them, where a base from another module would not be in scope.
        """

        signature = tuple(f.signature for f in fields)

        if (twin := self._by_signature.get(signature)) is not None:
            self.models.append(Model(name, [], base=twin.name, inherited=list(fields)))
            return name

        base, inherited = self._best_base(fields)
        model = Model(name, fields[len(inherited):], base=base, inherited=inherited, inline=inline)

        self.models.append(model)
        self._by_signature[signature] = model
        return name

    def _best_base(self, fields: list[ModelField]) -> tuple[str, list[ModelField]]:
        best: Optional[Model] = None

        for candidate in self.models:
            depth = len(candidate.signature)

            if not 0 < depth < len(fields):
                continue
            if candidate.signature != tuple(f.signature for f in fields[:depth]):
                continue
            if best is None or depth > len(best.signature):
                best = candidate

        if best is None:
            return MODEL_BASE, []

        return best.name, fields[:len(best.signature)]


