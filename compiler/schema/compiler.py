@dataclass
class ModelField:
    name: str
    type_expr: str
    default: Any = REQUIRED
    constraints: dict[str, Any] = field(default_factory=dict)
    doc: Optional[str] = None


    @property
    def signature(self) -> tuple:
        default = literal(self.default) if self.default is not REQUIRED else None
        return (self.name, self.type_expr, default)

    def render(self, imports: Imports) -> str:
        imports.use_expr(self.type_expr)
        line = f"{INDENT}{self.name}: {self.type_expr}"

        if self.constraints:
            imports.add(PYDANTIC_MODULE, FIELD_HELPER)
            args = [literal(self.default)] if self.default is not REQUIRED else []
            args += [f"{CONSTRAINTS[k]}={literal(v)}" for k, v in sorted(self.constraints.items())]
            line += f" = {FIELD_HELPER}({', '.join(args)})"

        elif self.default is not REQUIRED:
            imports.use_expr(literal(self.default))
            line += f" = {literal(self.default)}"

        if self.doc:
            line += "\n" + docstring(self.doc, INDENT)

        return line


@dataclass
class Enum:
    name: str
    values: list[str]
    inline: tuple = ()

    package = ENUM_PACKAGE

    @property
    def module(self) -> str:
        return snake(self.name)

    def render(self, imports: Imports) -> str:
        imports.add(ENUM_STDLIB_MODULE, ENUM_AUTO)
        imports.add(COMPAT_MODULE, ENUM_BASE)

        members = "\n".join(f"{INDENT}{value.upper()} = {ENUM_AUTO}()" for value in self.values)
        return f"class {self.name}({ENUM_BASE}):\n{members}"


@dataclass
class Model:
    name: str
    fields: list[ModelField]
    base: str = MODEL_BASE
    inherited: list[ModelField] = field(default_factory=list)

    # Anonymous models this one is built out of. They are written into the
    # same file rather than getting one of their own -- see `emit_unit`.
    inline: list["Model"] = field(default_factory=list)

    package = TYPE_PACKAGE

    @property
    def module(self) -> str:
        return snake(self.name)

    @property
    def signature(self) -> tuple:
        return tuple(f.signature for f in self.inherited + self.fields)

    def render(self, imports: Imports) -> str:
        if self.base == MODEL_BASE:
            imports.add(BASE_MODULE, MODEL_BASE)
        else:
            imports.use(self.base)

        body = render_fields(self.fields, imports) or f"{INDENT}pass"
        return f"class {self.name}({self.base}):\n{body}"


@dataclass
class Alias:
    """A result that is a bare container rather than an object."""

    name: str
    expr: str
    doc: Optional[str] = None
    inline: list[Model] = field(default_factory=list)

    package = TYPE_PACKAGE

    @property
    def module(self) -> str:
        return snake(self.name)

    def render(self, imports: Imports) -> str:
        imports.use_expr(self.expr)
        line = f"{self.name} = {self.expr}"

        if not self.doc:
            return line

        # A comment, not a docstring: PEP 224 attribute docs do not attach to
        # a module-level type alias, so a docstring here would be a stray
        # expression statement.
        comment = "\n".join(f"# {part}".rstrip() for part in self.doc.split("\n"))
        return f"{comment}\n{line}"


@dataclass
class Method:
    name: str
    verb: str
    returning: str
    description: str
    fields: list[ModelField]
    errors: dict[str, dict[str, str]] = field(default_factory=dict)
    inline: list[Model] = field(default_factory=list)

    package = METHOD_PACKAGE

    @property
    def module(self) -> str:
        return snake(self.name)

    def raises(self) -> str:
        """The `Raises:` section, naming the exception class per error id.

        The class names follow the same SCREAMING_SNAKE -> PascalCase rule the
        error generator uses, so every name here resolves to a real class in
        `WolfTg.errors`.
        """

        if not self.errors:
            return ""

        lines = [RAISES_HEADER]

        for code in sorted(self.errors, key=int):
            for error_id, message in sorted(self.errors[code].items()):
                lines.append(RAISES_LINE.format(
                    indent=INDENT, exception=pascal(error_id), code=code, message=message,
                ))

        return "\n".join(lines)

    def render(self, imports: Imports) -> str:
        imports.add(BASE_MODULE, METHOD_BASE)
        imports.use(self.returning)

        text = "\n\n".join(filter(None, [self.description, self.raises()]))

        head = f"class {self.name}({METHOD_BASE}[{self.returning}]):"
        doc = docstring(text, INDENT) if text else ""
        attrs = (
            f"{INDENT}{RETURNING_ATTR} = {self.returning}\n"
            f'{INDENT}{REQUEST_METHOD_ATTR} = "{self.verb}"'
        )

        return "\n\n".join(filter(None, [
            head + ("\n" + doc if doc else ""),
            attrs,
            render_fields(self.fields, imports),
        ]))


