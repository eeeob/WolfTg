def reset(package: str) -> None:
    """Clear a package of everything it did not write by hand."""

    folder = DEST / package
    folder.mkdir(parents=True, exist_ok=True)

    for path in folder.glob(f"*{PY_EXT}"):
        if path.stem != KEPT_MODULE:
            path.unlink()

    shutil.rmtree(folder / PYCACHE, ignore_errors=True)


def write(relative: str, *blocks: str) -> None:
    text = "\n\n".join(b for b in blocks if b).strip() + "\n"
    (DEST / relative).write_text(text, encoding=ENCODING)


def emit_unit(unit, table: dict[str, tuple[str, str]]) -> None:
    imports = Imports(table, unit.package)

    # Rendering is what discovers the imports, so it has to come first. The
    # anonymous models go above the unit that uses them, innermost first.
    bodies = [model.render(imports) for model in unit.inline]
    bodies.append(unit.render(imports))

    write(
        f"{unit.package}/{unit.module}{PY_EXT}",
        HEADER,
        imports.render(),
        "\n\n".join(bodies),
        render_all([unit.name]),
    )


def emit_init(package: str, modules: list[str], exported: list[str]) -> None:
    """Re-export the package's public surface.

    Every module is star-imported so its symbol lands in the package
    namespace, but `__all__` lists only the public names: the anonymous nested
    models stay reachable for anyone who needs them without becoming part of
    `from WolfTg.types import *`.
    """

    write(
        f"{package}/{INIT_MODULE}{PY_EXT}",
        HEADER,
        "\n".join(f"from .{m} import *" for m in sorted(modules)),
        render_all(sorted(exported)),
    )


