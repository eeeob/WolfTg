# ===========================================================================
# Rendering helpers
# ===========================================================================

REQUIRED = object()  # sentinel: field has no default


class Raw(str):
    """A default that is already Python source -- an enum member, say."""



def snake(text: str) -> str:
    return ("_" if text.startswith("_") else "") + _SNAKE2_PATTERN.sub(
        r"\1_\2", _SNAKE1_PATTERN.sub(r"\1_\2", text)
    ).lower()

def pascal(text: str) -> str:
    return "".join(i.capitalize() for i in snake(text).split("_") if i)

def literal(value: Any) -> str:
    return str(value) if isinstance(value, Raw) else repr(value)


def derive_model_name(path: str) -> str:
    """Name an anonymous nested object after where it sits.

    `GetCountryInfo.result.buy_options.value` -> `_GetCountryInfoBuyOptions`
    `AvailableCountries.result|1.value.value` -> `_AvailableCountriesResultItem`
    """

    method, *rest = [re.sub(r"\|\d+$", "", part) for part in path.split(".")]

    # Trailing map-value hops mean "the thing inside this map" -- they carry no
    # name of their own, so drop them and remember we went through a map.
    mapped = False

    while rest and rest[-1] == VALUE_SEGMENT:
        rest.pop()
        mapped = True

    # Every response path starts at `result`, which only earns a place in the
    # name when nothing more specific followed it.
    if len(rest) > 1 and rest[0] == RESULT_KEY:
        rest.pop(0)

    if mapped and rest == [RESULT_KEY]:
        rest.append(MAP_ITEM_SUFFIX)

    return PRIVATE_PREFIX + method + "".join(pascal(part) for part in rest)


def map_key_names(text: str) -> list[str]:
    """Key names from the `{section: {country_code: price}}` prose notation.

    The schema documents the keys of an open-ended map in `x-variants` rather
    than in `propertyNames`, outermost first. Reading them back is what lets a
    country-keyed map land on `RegionCode` instead of a bare `str`.
    """

    return list(dict.fromkeys(re.findall(r"\{(\w+):", text)))


def tokens(expr: str) -> list[str]:
    """The identifiers inside a rendered type expression."""

    return re.findall(r"[A-Za-z_][A-Za-z0-9_]*", expr)


def docstring(text: str, indent: str) -> str:
    """Render `text` as a docstring, escaping anything that would break out."""

    body = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = body.split("\n")

    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""'

    out = [f'{indent}"""{lines[0]}']
    out += [f"{indent}{line}".rstrip() for line in lines[1:]]
    out.append(f'{indent}"""')
    return "\n".join(out)


def render_all(names: list[str]) -> str:
    body = "".join(f'    "{name}", \n' for name in names)
    return f"__all__ = (\n{body})"


def base_exports(package: str) -> list[str]:
    """The `__all__` of a package's hand-written kept module, read not assumed."""

    path = DEST / package / f"{KEPT_MODULE}{PY_EXT}"

    if not path.exists():
        return []

    for node in ast.walk(ast.parse(path.read_text(encoding=ENCODING))):
        if not isinstance(node, ast.Assign):
            continue
        if not any(getattr(t, "id", None) == "__all__" for t in node.targets):
            continue

        return [e.value for e in node.value.elts if isinstance(e, ast.Constant)]

    return []


def render_fields(fields: list["ModelField"], imports: "Imports") -> str:
    """Render a field block, spacing out only the ones carrying a docstring.

    Bare `name: type` lines read better packed together; a documented field
    needs air around it so its docstring cannot be mistaken for belonging to
    the field below.
    """

    out = []

    for i, f in enumerate(fields):
        if i and (f.doc or fields[i - 1].doc):
            out.append("")

        out.append(f.render(imports))

    return "\n".join(out)


# ===========================================================================
# Imports
# ===========================================================================

class Imports:
    """Resolves symbols to import lines for one generated module.

    A symbol defined in the same package is imported from its own module
    rather than through the package `__init__`, so the generated modules do
    not depend on their package being fully initialised first.
    """

    def __init__(self, table: dict[str, tuple[str, str]], package: str) -> None:
        self.table = table
        self.package = package
        self._by_module: dict[str, set[str]] = {}

    def add(self, module: str, name: str) -> str:
        self._by_module.setdefault(module, set()).add(name)
        return name

    def use(self, symbol: str) -> None:
        """Import `symbol` from wherever it is defined, if it needs importing."""

        if symbol in TYPING_NAMES:
            self.add(TYPING_MODULE, symbol)

        elif symbol in SCALAR_NAMES:
            self.add(TYPINGS_MODULE, symbol)

        elif (location := self.table.get(symbol)) is not None:
            package, module = location
            self.add(f".{module}" if package == self.package else f"..{package}", symbol)

    def use_expr(self, expr: str) -> None:
        for symbol in tokens(expr):
            self.use(symbol)

    def render(self) -> str:
        ranked = sorted(
            self._by_module.items(),
            key=lambda item: (
                IMPORT_ORDER.index(item[0]) if item[0] in IMPORT_ORDER else len(IMPORT_ORDER),
                item[0],
            ),
        )
        lines = [f"from {module} import {', '.join(sorted(names))}" for module, names in ranked]

        external = [line for line in lines if not line.startswith("from .")]
        local = [line for line in lines if line.startswith("from .")]

        return "\n\n".join(filter(None, ["\n".join(external), "\n".join(local)]))


