def build(source: dict) -> Registry:
    registry = Registry()
    compiler = TypeCompiler(registry, source.get(DEFS_KEY, {}))

    for name, spec in source[ENDPOINTS_KEY].items():
        result_schema = spec[RESPONSE_KEY][PROPERTIES_KEY][RESULT_KEY]
        result_path = f"{name}.{RESULT_KEY}"

        # Every method gets its own `{Method}Result`, even where two methods
        # return the same shape -- the repeat is emitted as an empty subclass,
        # so both names exist and neither shape is written twice.
        returning = f"{name}{RESULT_SUFFIX}"

        if PROPERTIES_KEY in result_schema:
            compiler.model(result_schema, result_path, returning)

        else:
            # A bare container (a map of maps) is a type alias, not a class.
            expr = compiler.compile(result_schema, result_path, RESULT_KEY)
            registry.aliases.append(Alias(
                returning, expr, result_schema.get(VARIANTS_KEY), compiler.take_inline(),
            ))

        request = spec.get(REQUEST_KEY) or {}
        fields = compiler.fields(request, f"{name}.{REQUEST_KEY}")

        registry.methods.append(Method(
            name=name,
            verb=spec[VERBS_KEY][0],
            returning=returning,
            description=spec.get(DESCRIPTION_KEY, ""),
            fields=fields,
            errors=spec.get(ERRORS_KEY) or {},
            inline=compiler.take_inline(),
        ))

    return registry


def start() -> None:
    source: dict = json.loads(SOURCE.read_text(encoding=ENCODING))

    print(f"compiling {len(source[ENDPOINTS_KEY])} methods from {SOURCE.name}")

    registry = build(source)
    table = registry.symbol_table()

    for package in PACKAGES:
        reset(package)

    for unit in registry.units:
        emit_unit(unit, table)

    for package in PACKAGES:
        units = [u for u in registry.units if u.package == package]

        # Each package keeps a hand-written module; only enums has none.
        kept = base_exports(package)
        modules = [u.module for u in units] + ([KEPT_MODULE] if kept else [])
        exported = [u.name for u in units if not u.name.startswith(PRIVATE_PREFIX)] + kept

        emit_init(package, modules, exported)
        print(f"  + {DEST.name}/{package}/ ({len(modules)} modules, {len(exported)} exported)")

    print(
        f"done: {len(registry.enums)} enums, {len(registry.models)} models, "
        f"{len(registry.aliases)} aliases, {len(registry.methods)} methods"
    )


if __name__ == "__main__":
    start()
