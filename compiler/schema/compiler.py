class TypeCompiler:
    """Turns schema nodes into type expressions, registering what they need.

    Only produces source text -- imports are resolved later, once every symbol
    has a home, by tokenizing the expressions this returns.

    Anonymous nested objects are collected in `_inline` as they are met, and
    handed to whichever unit is being built via `take_inline()`. Two units
    needing the same shape each get their own copy, which keeps every
    generated file readable on its own.

    `defs` is the schema's `$defs` table -- every named, reusable shape a
    `$ref` can point at. Resolving a ref just compiles the pointed-to schema,
    so a `$ref`'d enum goes through the same titled/untitled rule as one
    written out in place, and de-dupes against it the same way.
    """

    def __init__(self, registry: Registry, defs: dict[str, dict]) -> None:
        self.registry = registry
        self.defs = defs
        self._inline: list[Model] = []

    def take_inline(self) -> list[Model]:
        """The anonymous models met since the last call, innermost first."""

        collected, self._inline = self._inline, []
        return collected

    def compile(self, schema: dict, path: str, name: str = "", keys: tuple = (), depth: int = 0) -> str:
        """`path` locates the node, `name` is the property it was reached
        through (for the scalar hints), and `keys`/`depth` carry the map key
        names documented in an enclosing `x-variants`."""

        # A node documenting its own map shape restarts the key trail.
        if variants := schema.get(VARIANTS_KEY):
            if found := map_key_names(variants):
                keys, depth = tuple(found), 0

        if REF_KEY in schema:
            return self._ref(schema[REF_KEY])

        if ENUM_KEY in schema:
            return self._enum(schema, path)

        if ANY_OF_KEY in schema:
            return self._any_of(schema[ANY_OF_KEY], path, name, keys, depth)

        if CONST_KEY in schema:
            return self._const(schema[CONST_KEY])

        kind = schema.get(TYPE_KEY)

        if kind == OBJECT_TYPE:
            return self._object(schema, path, name, keys, depth)

        if kind == NULL_TYPE:
            return NONE_TYPE

        if kind in PRIMITIVES:
            return SCALAR_HINTS.get((name, kind)) or PRIMITIVES[kind]

        return ANY_TYPE

    # --- branches ---

    def _ref(self, ref: str) -> str:
        def_name = ref.removeprefix(REF_PREFIX)
        return self.compile(self.defs[def_name], f"{DEFS_KEY}.{def_name}", def_name)

    def _enum(self, schema: dict, path: str) -> str:
        """A titled enum becomes a class; an untitled one stays a `Literal`.

        The title is the schema saying "this value set is a thing with a name
        and a life of its own". Without one, the members are just the values
        this one field accepts, and inlining them keeps a single-use set from
        becoming a public class nobody asked for.
        """

        values = schema[ENUM_KEY]

        if title := schema.get(TITLE_KEY):
            return self.registry.enum(title, values, path)

        return f"{LITERAL_TYPE}[{', '.join(repr(v) for v in values)}]"

    def _const(self, value: Any) -> str:
        kind = {bool: "boolean", int: "integer", float: "number", str: "string"}.get(type(value))
        return PRIMITIVES[kind] if kind else ANY_TYPE

    def _any_of(self, members: list[dict], path: str, name: str, keys: tuple, depth: int) -> str:
        nullable = any(m.get(TYPE_KEY) == NULL_TYPE for m in members)
        real = [m for m in members if m.get(TYPE_KEY) != NULL_TYPE]

        # `int | float` is the API's way of spelling "a decimal amount"; the
        # SDK has one name for that.
        if {m.get(TYPE_KEY) for m in real} == set(NUMBER_UNION):
            exprs = [NUMBER_TYPE]
        else:
            # Alternatives sit side by side, so they all start at this depth.
            exprs = [self.compile(m, f"{path}|{i}", name, keys, depth) for i, m in enumerate(real)]

        exprs = list(dict.fromkeys(exprs))
        expr = self._merge_maps(exprs) if len(exprs) > 1 else exprs[0]

        return f"{OPTIONAL_TYPE}[{expr}]" if nullable else expr

    def _merge_maps(self, exprs: list[str]) -> str:
        """Union alternatives, factoring a shared `Dict[K, ...]` prefix inward.

        `Dict[K, A] | Dict[K, B]` is really "a map of K to either" -- saying it
        that way keeps the alternation on the leaf, where it belongs.
        """

        prefixes = {e.split(", ", 1)[0] for e in exprs}

        if len(prefixes) == 1 and all(e.startswith(f"{DICT_TYPE}[") for e in exprs):
            prefix = prefixes.pop()
            values = [e[len(prefix) + 2:-1] for e in exprs]
            return f"{prefix}, {self._merge_maps(values) if len(set(values)) > 1 else values[0]}]"

        return f"{UNION_TYPE}[{', '.join(exprs)}]"

    def _object(self, schema: dict, path: str, name: str, keys: tuple, depth: int) -> str:
        if PROPERTIES_KEY in schema:
            return self._inline_model(schema, path)

        value_schema = schema.get(ADDITIONAL_KEY)

        if not isinstance(value_schema, dict):
            return f"{DICT_TYPE}[{DEFAULT_KEY_TYPE}, {ANY_TYPE}]"

        # `propertyNames` states the key set outright (inline or via `$ref`);
        # failing that, fall back to the name the prose gave this depth, run
        # through the scalar hints.
        if names := schema.get(PROPERTY_NAMES_KEY):
            key = self.compile(names, f"{path}.{PROPERTY_NAMES_KEY}")
        else:
            documented = keys[depth] if depth < len(keys) else ""
            key = SCALAR_HINTS.get((documented, "string"), DEFAULT_KEY_TYPE)

        value = self.compile(value_schema, f"{path}.{VALUE_SEGMENT}", name, keys, depth + 1)
        return f"{DICT_TYPE}[{key}, {value}]"

    # --- model building ---

    def fields(self, schema: dict, path: str) -> list[ModelField]:
        required = set(schema.get(REQUIRED_KEY, ()))
        fields = [
            self.field(prop, prop_schema, self.compile(prop_schema, f"{path}.{prop}", prop), prop in required)
            for prop, prop_schema in schema.get(PROPERTIES_KEY, {}).items()
        ]

        # Required first: the schema mostly orders them that way already, and
        # pydantic does not care, but it reads better and keeps diffs stable.
        fields.sort(key=lambda f: f.default is not REQUIRED)
        return fields

    def model(self, schema: dict, path: str, name: str) -> str:
        """Build a public result model, taking any anonymous models with it."""

        fields = self.fields(schema, path)
        return self.registry.model(name, fields, self.take_inline())

    def _inline_model(self, schema: dict, path: str) -> str:
        """Build an anonymous model, to be written into the caller's file.

        Reused within the unit being built, duplicated across units -- the
        alternative is a shared module per shape, which buries a two-field
        helper in a file of its own.
        """

        fields = self.fields(schema, path)
        signature = tuple(f.signature for f in fields)

        for existing in self._inline:
            if existing.signature == signature:
                return existing.name

        self._inline.append(model := Model(derive_model_name(path), fields))
        return model.name

    def field(self, name: str, schema: dict, type_expr: str, required: bool) -> ModelField:
        constraints = {k: v for k, v in schema.items() if k in CONSTRAINTS}
        doc = schema.get(DESCRIPTION_KEY)

        if required:
            return ModelField(name, type_expr, REQUIRED, constraints, doc)

        default = schema.get(DEFAULT_KEY)

        # A null default only makes sense on an optional type; the schema
        # usually spells that out via `anyOf`, but not always.
        if default is None and not type_expr.startswith(f"{OPTIONAL_TYPE}["):
            type_expr = f"{OPTIONAL_TYPE}[{type_expr}]"

        # An enum's default is a wire value; name the member instead.
        elif type_expr in self.registry.enum_members:
            default = Raw(f"{type_expr}.{str(default).upper()}")

        return ModelField(name, type_expr, default, constraints, doc)


