PACKAGES = ("enums", "types", "methods")
KEPT_MODULE = "base"

# Which package each kind of generated symbol belongs to.
ENUM_PACKAGE = "enums"
TYPE_PACKAGE = "types"
METHOD_PACKAGE = "methods"

HEADER = """
# This file is auto-generated by the schema generator.
# Do not edit manually.
""".strip()

