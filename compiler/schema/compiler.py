# --- SDK names the generated code binds to ---------------------------------

# Base classes, and the module each comes from relative to its own package.
MODEL_BASE = "ApiObject"
METHOD_BASE = "ApiMethod"
ENUM_BASE = "StrEnum"

BASE_MODULE = f".{KEPT_MODULE}"
COMPAT_MODULE = ".._compat"
TYPINGS_MODULE = "..utils.typings"
ENUM_STDLIB_MODULE = "enum"
ENUM_AUTO = "auto"

TYPING_MODULE = "typing"
PYDANTIC_MODULE = "pydantic"
FIELD_HELPER = "Field"

# The two class attributes every `ApiMethod` subclass declares.
RETURNING_ATTR = "__returning__"
REQUEST_METHOD_ATTR = "__request_method__"

# --- naming rules ----------------------------------------------------------

# `GetBalance` -> `GetBalanceResult`.
RESULT_SUFFIX = "Result"

# Marks a model that is nested inside a result rather than named by the API.
PRIVATE_PREFIX = "_"

# Appended when an anonymous model sits directly under `result`, with no
# property name of its own to borrow: `_AvailableCountriesResultItem`.
MAP_ITEM_SUFFIX = "item"

# A segment the compiler appends to a schema path as it descends into a map,
# marking a step with no property name of its own. It shows up in derived
# model names, so it reads as a word: `GetCountryInfo.result.buy_options.value`.
VALUE_SEGMENT = "value"

# (field name, JSON type) -> validated scalar from `WolfTg.utils.typings`.
# Keyed on the type too, because the same name means different things at
# different types: `code` is an OTP string on the way in but a plain int on
# the way out, and `country_code` is an ISO region in but a dialing prefix out.
SCALAR_HINTS: dict[tuple[str, str], str] = {
    ("phone_number", "string"): "ValidPhoneNumber",
    ("country_code", "string"): "ValidRegionCode",
    ("region_code", "string"): "ValidRegionCode",
    ("code", "string"): "ValidTgOtpCode",
}

# --- type expressions ------------------------------------------------------

# The `typing` names the generated annotations are built from.
DICT_TYPE = "Dict"
UNION_TYPE = "Union"
OPTIONAL_TYPE = "Optional"
ANY_TYPE = "Any"
NONE_TYPE = "None"

# What an enum the schema never titled compiles to, inline at the use site.
LITERAL_TYPE = "Literal"

# The one name for "an int or a float" -- the API spells amounts either way.
NUMBER_TYPE = "Number"

# Key type for an open-ended map the schema never describes.
DEFAULT_KEY_TYPE = "str"

# Imported from `typing`; everything else there is left alone.
TYPING_NAMES = frozenset((
    ANY_TYPE, DICT_TYPE, LITERAL_TYPE, OPTIONAL_TYPE, UNION_TYPE, "List", "Tuple",
))

# Imported from TYPINGS_MODULE. `Number` arrives there from `pytools.typings`,
# which `WolfTg.utils.typings` re-exports wholesale.
SCALAR_NAMES = frozenset(SCALAR_HINTS.values()) | {NUMBER_TYPE}

# Import blocks, in the order they are written out. Anything unlisted (a
# sibling module in the same package) sorts after these, alphabetically.
IMPORT_ORDER = (
    TYPING_MODULE,
    PYDANTIC_MODULE,
    ENUM_STDLIB_MODULE,
    COMPAT_MODULE,
    TYPINGS_MODULE,
    f"..{ENUM_PACKAGE}",
    f"..{TYPE_PACKAGE}",
)

# --- schema vocabulary -----------------------------------------------------

# Top-level shape of the source dump: named schemas endpoints are free to
# reference, and the endpoints themselves.
